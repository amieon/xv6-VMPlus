/*
 * shm_test1.c - 共享内存功能测试程序
 * 
 * 该程序用于验证内核的共享内存机制是否正常工作。共享内存是一种进程间通信方式，
 * 允许不同进程访问同一段物理内存区域，从而实现高效的数据共享。
 * 
 * 测试流程：
 * 1. 创建一个4096字节的共享内存区域（使用MAP_SHARED标志）
 * 2. 父进程将共享内存的第一个字节设置为7
 * 3. 子进程等待一段时间后读取共享内存的第一个字节并打印
 * 4. 子进程将共享内存的第一个字节设置为42并打印
 * 5. 父进程等待子进程结束后，读取共享内存的第一个字节并打印
 * 6. 如果父进程能看到子进程写入的42，说明共享内存机制正常工作
 * 
 * 关键技术点：
 * - 使用mmap系统调用创建共享内存（MAP_ANON|MAP_SHARED）
 * - 使用相同的key确保父子进程映射到同一段共享内存
 * - 使用fork创建子进程，继承父进程的内存映射
 */

#include "../kernel/types.h"
#include "../kernel/stat.h"
#include "user.h"

/*
 * main - 程序入口函数
 * 
 * 执行共享内存功能测试
 * 
 * 参数：
 *   无
 * 
 * 返回值：
 *   成功时返回0，失败时返回1
 */
int main(void){
  int key = 1;  /* 共享内存键值，用于标识共享内存对象 */
  
  /* 创建共享内存映射：
   * - 起始地址0（让系统分配）
   * - 长度4096字节
   * - 可读写权限
   * - 匿名映射 + 共享映射
   * - 键值为1
   */
  char *p = mmap(0, 4096, PROT_READ|PROT_WRITE, MAP_ANON|MAP_SHARED, key);
  if(p == (char*)-1){ 
    printf("mmap fail\n"); 
    exit(1); 
  }

  /* 创建子进程 */
  int pid = fork();
  
  if(pid == 0){
    // 子进程执行路径
    /* 短暂延迟，确保父进程有足够时间写入数据 */
    for(int i=1; i<10000000; ++i)
        ;
    
    /* 读取共享内存中的值并打印 */
    printf("child sees: %d\n", p[0]);
    
    /* 修改共享内存中的值 */
    p[0] = 42;
    printf("child wrote 42\n");
    
    /* 解除共享内存映射 */
    munmap(p, 4096);
    exit(0);
  } else {
    // 父进程执行路径
    /* 向共享内存写入初始值 */
    p[0] = 7;
    printf("parent wrote 7\n");
    
    /* 等待子进程结束 */
    wait(0);
    
    /* 读取子进程修改后的值并打印 */
    printf("parent sees after child: %d\n", p[0]);
    
    /* 解除共享内存映射 */
    munmap(p, 4096);
    exit(0);
  }
}
